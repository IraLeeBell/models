FENCE = re.compile(r"^```.*?^```", re.S | re.M)
CODE_SPAN = re.compile(r"(`+)[^\n]+?\1")
RELATIVE_LINK = re.compile(r"\]\((?![a-z][a-z0-9+.-]*:|#)([^)\s]+)\)")
PATTERN_FILES = {"generate.py", "digest_check.py"}  # define the banned patterns themselves


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tracked_files():
    try:
        result = subprocess.run(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
                                cwd=REPO, capture_output=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        return None
    return [REPO / name for name in result.stdout.decode().split("\0") if name]


def local_sources(model, catalog, extraction_dir=None):
    """Concatenate whatever full-text sources exist locally for the copy check, or return None."""
    texts = []
    doc_ids = ([model["document"]] if model.get("document") else []) + model.get("supplements", [])
    for doc_id in doc_ids:
        doc = catalog["documents"][doc_id]
        folder = ROOT / model["slug"]
        if doc_id == model.get("document"):
            candidates = [folder / ("system-card.md" if doc["format"] == "pdf" else "model-card.md")]
        else:
            candidates = [folder / "supplements" / f"{doc_id}.md"]
        if extraction_dir:
            candidates.append(Path(extraction_dir) / f"{doc_id}.md")
        found = next((p for p in candidates if p.is_file()), None)
        if found:
            texts.append(found.read_text(encoding="utf-8"))
    return "\n".join(texts) if texts else None


def check(catalog, extraction_dir=None):
    import card_extract  # needs PyMuPDF only for --check; imported lazily so --write stays stdlib-only

    problems, documents = [], catalog["documents"]
    for path, text in outputs(catalog).items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            problems.append(f"{path.relative_to(REPO)} is stale; run generate.py --write")
    slugs = {m["slug"] for m in catalog["models"]}
    folders = {p.name for p in ROOT.iterdir() if p.is_dir() and not p.name.startswith((".", "_"))}
    if folders != slugs:
        problems.append(f"folders differ from catalog: extra {sorted(folders - slugs)}, missing {sorted(slugs - folders)}")
    skipped = []
    for model in catalog["models"]:
        source = local_sources(model, catalog, extraction_dir)
        if source is None and model.get("document"):
            skipped.append(model["slug"])
        problems += digest_check.check(model, documents, ROOT, extraction=source)

    gitignore = (ROOT / ".gitignore").read_text(encoding="utf-8").splitlines()
    for doc_id, doc in documents.items():
        for model, role in users(catalog)[doc_id]:
            if doc["rights"] != "granted" or role != "primary":
                continue
            folder = ROOT / model["slug"]
            license_path = folder / doc["license_file"]
            if not license_path.is_file() or sha256(license_path) != doc["license_sha256"]:
                problems.append(f"{model['slug']}: {doc['license_file']} is missing or differs from the catalog")
            if doc["format"] == "pdf":
                pdf, md = folder / "system-card.pdf", folder / "system-card.md"
                for name in (f"!{model['slug']}/system-card.pdf", f"!{model['slug']}/system-card.md"):
                    if name not in gitignore:
                        problems.append(f".gitignore lacks {name}")
                if not pdf.is_file() or sha256(pdf) != doc["sha256"]:
                    problems.append(f"{model['slug']}: committed PDF is missing or its SHA-256 differs")
                if not md.is_file():
                    problems.append(f"{model['slug']}: committed extraction is missing")
                else:
                    text = md.read_text(encoding="utf-8")
                    if not card_extract.check_markdown(text, doc["pages"]) or doc["sha256"] not in text[:3000]:
                        problems.append(f"{model['slug']}: system-card.md lacks page markers or the PDF's SHA-256")
            else:
                card = folder / "model-card.md"
                if f"!{model['slug']}/model-card.md" not in gitignore:
                    problems.append(f".gitignore lacks !{model['slug']}/model-card.md")
                if not card.is_file() or sha256(card) != doc["sha256"]:
                    problems.append(f"{model['slug']}: model-card.md is missing or differs from the owner file")

    files = tracked_files()
    if files is not None:
        granted = {ROOT / m["slug"] / name for doc_id, doc in documents.items() if doc["rights"] == "granted"
                   for m, role in users(catalog)[doc_id] if role == "primary"
                   for name in ("system-card.pdf", "system-card.md", "model-card.md")}
        committed = set(files)
        committed_dirs = {parent for path in files for parent in path.parents}
        for path in files:
            if path.suffix == ".md" and path.name not in ("system-card.md", "model-card.md") and path.is_file():
                prose = CODE_SPAN.sub("", FENCE.sub("", path.read_text(encoding="utf-8")))
                for target in RELATIVE_LINK.findall(prose):
                    resolved = Path(os.path.normpath(path.parent / target.split("#")[0]))
                    if resolved not in committed and resolved not in committed_dirs:
                        problems.append(f"{path.relative_to(REPO)} links to {target}, which would not be committed")
            if path.suffix.lower() == ".pdf" and path not in granted:
                problems.append(f"{path.relative_to(REPO)} would be committed without a recorded grant")
            if path.name in ("system-card.md", "model-card.md") and path not in granted:
                problems.append(f"{path.relative_to(REPO)} would be committed without a recorded grant")
            verbatim = path.name in ("system-card.md", "model-card.md") or path.name.startswith("LICENSE")
            if path.suffix in (".md", ".json", ".py", ".txt") and not verbatim and path.is_file():
                match = BANNED.search(path.read_text(encoding="utf-8"))
                if match and path.name not in PATTERN_FILES and not path.name.startswith("test_"):
                    problems.append(f"{path.relative_to(REPO)} contains banned text {match.group(0)!r}")
    if skipped:
        print(f"note: copy check skipped for {len(skipped)} digests without a local extraction "
              "(run local_cards.py --all to enable it)")
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="write generated Markdown")
    parser.add_argument("--check", action="store_true", help="verify the repository")
    parser.add_argument("--extraction-dir", type=Path,
                        help="directory of <document-id>.md extractions used for the digest copy check")
    args = parser.parse_args(argv)
    if not (args.write or args.check):
        parser.error("choose --write and/or --check")
    catalog = load_catalog()
    if args.write:
        for path, text in outputs(catalog).items():
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path.relative_to(REPO)}")
    if args.check:
        problems = check(catalog, args.extraction_dir)
        print("\n".join(problems) or f"catalog OK: {len(catalog['models'])} models, {len(catalog['documents'])} documents")
        return 1 if problems else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
