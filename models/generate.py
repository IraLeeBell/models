class CatalogError(ValueError):
    """catalog.json is inconsistent."""


def owner_url(url, publisher):
    parsed = urlparse(url)
    prefix = PUBLISHER_HOSTS[publisher].get(parsed.hostname or "")
    return parsed.scheme == "https" and prefix is not None and parsed.path.startswith(prefix)


def load_catalog(path=ROOT / "catalog.json"):
    catalog = json.loads(Path(path).read_text(encoding="utf-8"))

    def need(condition, message):
        if not condition:
            raise CatalogError(message)

    need(catalog.get("schema_version") == 2, "schema_version must be 2")
    for key in ("checked_at", "app_picker_checked_at"):
        need(DATE.fullmatch(str(catalog.get(key, ""))), f"{key} must be YYYY-MM-DD")
    for key in ("docs_revision", "docs_tables_commit"):
        need(REVISION.fullmatch(str(catalog.get(key, ""))), f"{key} must be a full commit SHA")
    documents, models = catalog["documents"], catalog["models"]
    for doc_id, doc in documents.items():
        need(SLUG.fullmatch(doc_id), f"unsafe document id {doc_id}")
        need(doc.get("publisher") in PUBLISHER_HOSTS, f"{doc_id}: unknown publisher")
        need(doc.get("format") in ("pdf", "markdown"), f"{doc_id}: format must be pdf or markdown")
        for key in ("title", "title_check", "url", "retrieved"):
            need(isinstance(doc.get(key), str) and doc[key].strip(), f"{doc_id}: {key} is required")
        need(DATE.fullmatch(doc["retrieved"]), f"{doc_id}: retrieved must be YYYY-MM-DD")
        need(PUBLISHED.fullmatch(doc.get("date") or "") or (doc.get("date") is None and doc.get("date_note")),
             f"{doc_id}: date must be YYYY-MM[-DD], or null with a date_note")
        need(SHA.fullmatch(doc.get("sha256", "")), f"{doc_id}: sha256 must be 64 hex digits")
        need(isinstance(doc.get("bytes"), int) and doc["bytes"] > 0, f"{doc_id}: bytes is required")
        if doc["format"] == "pdf":
            need(isinstance(doc.get("pages"), int) and doc["pages"] > 0, f"{doc_id}: pages is required")
        else:
            need(doc.get("pages") is None, f"{doc_id}: a non-PDF document has no page count")
        for url in [doc["url"], doc.get("resolved_url")] + [r["url"] for r in doc.get("other_revisions", [])]:
            if url:
                need(owner_url(url, doc["publisher"]), f"{doc_id}: {url} is not an owner URL")
        if doc.get("landing_url"):
            need(urlparse(doc["landing_url"]).scheme == "https", f"{doc_id}: landing_url must be https")
        for revision in doc.get("other_revisions", []):
            need(SHA.fullmatch(revision.get("sha256", "")) and revision.get("note"),
                 f"{doc_id}: other_revisions need sha256 and note")
        need(doc.get("rights") in ("granted", "not-granted"), f"{doc_id}: rights must be granted or not-granted")
        if doc["rights"] == "granted":
            for key in ("rights_basis", "license_file", "license_name", "license_url", "license_sha256", "copyright"):
                need(doc.get(key), f"{doc_id}: granted rights need {key}")
        else:
            need(doc["publisher"] in TERMS, f"{doc_id}: no terms recorded for {doc['publisher']}")

    slugs, names = Counter(m["slug"] for m in models), Counter(m["name"] for m in models)
    need(max(slugs.values()) == 1 and max(names.values()) == 1, "duplicate model slug or name")
    used = set()
    for model in models:
        slug = model["slug"]
        need(SLUG.fullmatch(slug), f"unsafe slug {slug}")
        need(model.get("provider") in PROVIDER_PUBLISHER, f"{slug}: unknown provider")
        need(model.get("lifecycle") in LIFECYCLE, f"{slug}: unknown lifecycle")
        need(model.get("cli") in CLI, f"{slug}: cli must be true, false, or auto-only")
        need(isinstance(model.get("summary"), str) and model["summary"], f"{slug}: summary is required")
        need(isinstance(model.get("scope"), str) and model["scope"], f"{slug}: scope is required")
        if model["lifecycle"] in ("current", "limited"):
            need(isinstance(model.get("app_picker_observed"), bool) and isinstance(model.get("app_auto"), bool),
                 f"{slug}: current models need app_picker_observed and app_auto")
            need(bool(model.get("copilot_id")) == model["app_picker_observed"],
                 f"{slug}: copilot_id is recorded only for models observed in the app picker")
        if model["lifecycle"] in ("retired", "limited"):
            need(DATE.fullmatch(model.get("retired_on", "")), f"{slug}: retired_on is required")
        if model["lifecycle"] == "retired":
            need(REVISION.fullmatch(model.get("last_listed_revision", "")), f"{slug}: last_listed_revision is required")
        doc_id = model.get("document")
        if doc_id is None:
            need(model.get("card_note"), f"{slug}: explain the missing publisher document in card_note")
        else:
            need(doc_id in documents, f"{slug}: unknown document {doc_id}")
            need(documents[doc_id]["publisher"] == PROVIDER_PUBLISHER[model["provider"]],
                 f"{slug}: document publisher does not match provider")
            need(model.get("scope_terms"), f"{slug}: scope_terms are required with a document")
            used.add(doc_id)
        for supplement in model.get("supplements", []):
            need(supplement in documents and supplement != doc_id, f"{slug}: bad supplement {supplement}")
            used.add(supplement)
        for related in model.get("related", []):
            need(related["slug"] in slugs, f"{slug}: related slug {related['slug']} is not in the catalog")
    need(used == set(documents), f"unused documents: {sorted(set(documents) - used)}")
    return catalog


def users(catalog):
    found = {doc_id: [] for doc_id in catalog["documents"]}
    for model in catalog["models"]:
        if model.get("document"):
            found[model["document"]].append((model, "primary"))
        for supplement in model.get("supplements", []):
            found[supplement].append((model, "supplement"))
    return found


def tables_url(revision, table="model-supported-clients.yml"):
    return f"https://github.com/github/docs/blob/{revision}/data/tables/copilot/{table}"


def commit_url(revision):
    return f"https://github.com/github/docs/commit/{revision}"


def size(value):
    return f"{value:,} bytes ({value / 1_048_576:.1f} MiB)" if value >= 1_048_576 else f"{value:,} bytes"


def dated(doc):
    return doc["date"] or "undated"


def doc_label(doc):
    if doc["format"] == "pdf":
        return f"PDF, {doc['pages']} pages"
    return "Markdown model card (owner's Hugging Face README; not a PDF)"


def files_for(model, catalog):
    """Return (committed, local_only) file descriptions for a model folder."""
    committed = [("digest.md", "original digest (this repository's MIT license)"),
                 ("digest.json", "structured version of the digest"),
                 ("source.md", "this provenance record (generated)"),
                 ("variants.md", "Copilot identifiers and related entries (generated)")]
    local = []
    doc = catalog["documents"].get(model.get("document"))
    if doc and doc["format"] == "pdf":
        pair = [("system-card.pdf", "the publisher's unmodified PDF"),
                ("system-card.md", "complete page-marked Markdown extraction of that PDF")]
        (committed if doc["rights"] == "granted" else local).extend(pair)
    elif doc:
        committed.append(("model-card.md", "the owner's Markdown model card, byte-for-byte"))
    if doc and doc["rights"] == "granted":
        committed.append((doc["license_file"], f"the publisher's {doc['license_name']}, which must accompany the copy"))
    for supplement in model.get("supplements", []):
        local.append((f"supplements/{supplement}.pdf", f"supplement PDF ({catalog['documents'][supplement]['title']})"))
        local.append((f"supplements/{supplement}.md", "page-marked extraction of the supplement"))
    return committed, local


def approval(doc):
    return (f"Written permission from {doc['publisher']} (the copyright holder) to publish, in the public "
            f"repository `{REPOSITORY}`, (1) an unmodified copy of the PDF \"{doc['title']}\" "
            f"(SHA-256 `{doc['sha256']}`) and (2) a complete verbatim Markdown extraction of it, with "
            "attribution. The grant should name the document or cover all of the publisher's system or "
            "model cards, and state any notice that must accompany the copy.")


def document_section(doc_id, doc, heading):
    lines = [heading, "", "| Field | Value |", "| --- | --- |",
             f"| Publisher | {doc['publisher']} |",
             f"| Title | {doc['title']} |",
             f"| Document date | {dated(doc)}{' (' + doc['date_note'] + ')' if doc.get('date_note') else ''} |",
             f"| Format | {doc_label(doc)} |",
             f"| Owner URL | <{doc['url']}> |"]
    if doc.get("resolved_url"):
        lines.append(f"| Redirects to | <{doc['resolved_url']}> |")
    if doc.get("landing_url"):
        lines.append(f"| Publisher landing page | <{doc['landing_url']}> |")
    lines += [f"| Retrieved | {doc['retrieved']} |",
              f"| Size | {size(doc['bytes'])} |",
              f"| SHA-256 | `{doc['sha256']}` |",
              f"| Catalog document ID | `{doc_id}` |", ""]
    if doc.get("other_revisions"):
        lines += ["Other revisions observed at owner URLs on the retrieval date (not used):", "",
                  "| URL | Size | Pages | SHA-256 | Note |", "| --- | --- | --- | --- | --- |"]
        for revision in doc["other_revisions"]:
            lines.append(f"| <{revision['url']}> | {revision['bytes']:,} bytes | {revision.get('pages') or ''} | "
                         f"`{revision['sha256']}` | {revision['note']} |")
        lines.append("")
    return lines


def rights_section(doc):
    if doc["rights"] == "granted":
        return [f"- **Decision: granted.** The complete document is committed with its license notice.",
                f"- **Basis:** {doc['rights_basis']}",
                f"- **License:** [{doc['license_name']}]({doc['license_url']}); copy in "
                f"[`{doc['license_file']}`]({doc['license_file']}) (SHA-256 `{doc['license_sha256']}`).",
                f"- **Attribution:** \"{doc['title']}\" by {doc['publisher']}, {dated(doc)}, <{doc['url']}>. "
                f"{doc['copyright']}; redistributed unmodified under the {doc['license_name']}.",
                "- **Optional confirmation:** the license names `license@moonshot.ai` for questions.", ""]
    name, url, finding = TERMS[doc["publisher"]]
    return ["- **Decision: not granted.** The PDF and its full text are linked and reproducible locally, "
            "not committed.",
            f"- **Basis:** No redistribution license appears in the document's text, links, or metadata. "
            f"[{name}]({url}): {finding} Public availability is not permission to republish.",
            f"- **Attribution for links and digest:** \"{doc['title']}\" by {doc['publisher']}, {dated(doc)}, "
            f"<{doc['url']}>. All rights in the document belong to {doc['publisher']}.",
            f"- **Approval needed to commit it:** {approval(doc)}", ""]


def render_source(model, catalog):
    documents = catalog["documents"]
    doc_id = model.get("document")
    doc = documents.get(doc_id)
    lines = [f"# Source provenance: {model['name']}", "", GENERATED, "",
             "## Copilot availability", "", "| Field | Value |", "| --- | --- |",
             f"| Lifecycle | {LIFECYCLE[model['lifecycle']]} |",
             f"| GitHub release status | {model['release_status']} |"]
    revision = model.get("last_listed_revision", catalog["docs_revision"])
    if model["cli"] == "auto-only":
        lines.append(f"| Copilot CLI | Auto selection only: in GitHub's [Auto model selection table]"
                     f"({tables_url(revision, 'auto-model-selection.yml')}), not yet a row in the per-client table |")
    else:
        lines.append(f"| Copilot CLI | {CLI[model['cli']]} ([per-client table]({tables_url(revision)})) |")
    if model["lifecycle"] in ("current", "limited"):
        picker = (f"Listed as `{model['copilot_id']}`" if model["app_picker_observed"] else "Not listed")
        lines += [f"| Copilot app model picker | {picker} (observed {catalog['app_picker_checked_at']}) |",
                  f"| Copilot app Auto selection | {'Eligible' if model['app_auto'] else 'Not listed'} "
                  f"([Auto table]({tables_url(revision, 'auto-model-selection.yml')})) |"]
    if model.get("retired_on"):
        lines.append(f"| GitHub retirement date | {model['retired_on']} ([retirement history]({RETIRED})) |")
    if model["lifecycle"] == "retired":
        lines.append(f"| Last listed in GitHub docs | [`{revision[:7]}`]({commit_url(revision)}) "
                     f"([frozen per-client table]({tables_url(revision)})) |")
    lines += [f"| Roster checked | {catalog['checked_at']} at github/docs [`{catalog['docs_revision'][:7]}`]"
              f"({commit_url(catalog['docs_revision'])}) ([supported models]({SUPPORTED})) |", ""]
    if model.get("note"):
        lines += [model["note"], ""]

    if doc:
        lines += document_section(doc_id, doc, "## Publisher document")
        lines += [f"**Scope for this model:** {model['scope']}", ""]
        lines += [f"**Scope check:** the downloaded document's first pages contain \"{doc['title_check']}\" and "
                  f"its text contains {', '.join(repr(t) for t in model['scope_terms'])}.", ""]
        if model.get("card_note"):
            lines += [model["card_note"], ""]
        for supplement in model.get("supplements", []):
            lines += document_section(supplement, documents[supplement], f"### Supplement: {documents[supplement]['title']}")
            lines += rights_section(documents[supplement])
        lines += ["## Redistribution permission", ""] + rights_section(doc)
    else:
        lines += ["## Publisher document", "",
                  "**None.** No publisher system card or model card exists for this model.", "",
                  f"**Scope:** {model['scope']}", "", model["card_note"], ""]

    committed, local = files_for(model, catalog)
    lines += ["## Files", "", "Committed in this folder:", ""]
    lines += [f"- [`{name}`]({name}): {text}" for name, text in committed]
    if local:
        lines += ["", "Local only (Git-ignored; create them with the workflow below):", ""]
        lines += [f"- `{name}`: {text}" for name, text in local]
    lines.append("")
    if doc:
        lines += ["## Reproduce or refresh locally", "", "```sh", "cd models",
                  "python3 -m pip install -r requirements-local.txt",
                  f"python3 local_cards.py --model {model['slug']}", "```", "",
                  "The script downloads from the owner URL, accepts only the publisher's hosts, checks the "
                  "content type, file signature, SHA-256, title, and model scope terms, then writes the files "
                  "above. A SHA-256 mismatch means the publisher revised the document; re-verify its scope "
                  "and update the catalog before trusting the new copy.", ""]
    return "\n".join(lines).rstrip() + "\n"


def link(model, target="digest.md", prefix="../"):
    return f"[{model['name']}]({prefix}{model['slug']}/{target})"


def status(model):
    label = LIFECYCLE[model["lifecycle"]]
    return f"{label} {model['retired_on']}" if model["lifecycle"] == "retired" else label


def render_variants(model, catalog):
    documents, by_slug = catalog["documents"], {m["slug"]: m for m in catalog["models"]}
    lines = [f"# Variants and related entries: {model['name']}", "", GENERATED, "",
             "## Copilot identifiers and settings", "", "| Surface | Identifier or setting | Evidence |",
             "| --- | --- | --- |",
             f"| GitHub supported-models tables | \"{model['name']}\" | [supported models]({SUPPORTED}) |"]
    if model.get("copilot_id"):
        efforts = model.get("app_reasoning_efforts") or []
        lines += [f"| Copilot app model picker | `{model['copilot_id']}` | observed {catalog['app_picker_checked_at']} |",
                  f"| App reasoning-effort options | {', '.join(efforts) if efforts else 'none offered'} | app picker |",
                  f"| App long-context option | {'offered' if model.get('app_long_context') else 'not offered'} | app picker |"]
    elif model["lifecycle"] in ("current", "limited"):
        lines.append(f"| Copilot app model picker | not listed | observed {catalog['app_picker_checked_at']} |")
    if model["lifecycle"] in ("current", "limited"):
        lines.append(f"| App Auto selection | {'eligible' if model['app_auto'] else 'not listed'} | GitHub Auto table |")
    lines.append(f"| Copilot CLI | {CLI[model['cli']].lower()} | GitHub per-client and Auto tables |")
    lines += ["", "Reasoning-effort and context options run the same model with different settings. They are "
              "not separate models and have no separate publisher cards. Picker observations reflect one "
              "account on one date; plans, policies, and rollouts change what a user sees.", ""]

    doc_id = model.get("document")
    lines += ["## Publisher document coverage", ""]
    if doc_id:
        doc = documents[doc_id]
        lines += [f"This folder uses [{doc['title']}]({doc['url']}) ({doc['publisher']}, {dated(doc)}). "
                  f"{model['scope']}", ""]
        shared = [m for m in catalog["models"] if m["slug"] != model["slug"]
                  and (m.get("document") == doc_id or doc_id in m.get("supplements", []))]
        if shared:
            lines += ["Other folders that use the same document:", ""]
            lines += [f"- {link(m, 'variants.md')} ({status(m)}): {m['scope']}" for m in shared]
            lines.append("")
        for supplement in model.get("supplements", []):
            sdoc = documents[supplement]
            lines += [f"Supplement: [{sdoc['title']}]({sdoc['url']}) ({dated(sdoc)}).", ""]
        revisions = doc.get("other_revisions", [])
        lines += [f"Document revision used: SHA-256 `{doc['sha256']}` ({doc_label(doc)})."]
        if revisions:
            lines.append(f"{len(revisions)} other revision(s) observed at owner URLs are listed in [source.md](source.md).")
        lines.append("")
    else:
        lines += ["No publisher card exists. " + model["card_note"], ""]

    series = [by_slug[s] for s in SERIES_ORDER(catalog, model)]
    if series:
        lines += [f"## {model['series']} series in this catalog", "", "| Model | Status | Publisher document |",
                  "| --- | --- | --- |"]
        for member in series:
            mdoc = documents.get(member.get("document"))
            title = f"[{mdoc['title']}]({mdoc['url']})" if mdoc else "none"
            name = f"**{member['name']}** (this folder)" if member is model else link(member, "variants.md")
            lines.append(f"| {name} | {status(member)} | {title} |")
        lines.append("")
    if model.get("related"):
        lines += ["## Related entries", ""]
        lines += [f"- {link(by_slug[r['slug']], 'variants.md')}: {r['relation']}." for r in model["related"]]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def SERIES_ORDER(catalog, model):
    if not model.get("series"):
        return []
    return [m["slug"] for m in catalog["models"] if m.get("series") == model["series"]]


def counts(catalog):
    models, documents = catalog["models"], catalog["documents"]
    lifecycle = Counter(m["lifecycle"] for m in models)
    formats = Counter(d["format"] for d in documents.values())
    granted = [d for d in documents.values() if d["rights"] == "granted"]
    return {
        "models": len(models), "current": lifecycle["current"], "limited": lifecycle["limited"],
        "utility": lifecycle["utility"], "retired": lifecycle["retired"],
        "documents": len(documents), "pdf": formats["pdf"], "markdown": formats["markdown"],
        "granted": len(granted), "not_granted": len(documents) - len(granted),
        "pdf_pages": sum(d["pages"] or 0 for d in documents.values()),
        "with_document": sum(1 for m in models if m.get("document")),
        "without_document": sum(1 for m in models if not m.get("document")),
        "cli": sum(1 for m in models if m["lifecycle"] in ("current", "limited") and m["cli"] is True),
        "cli_auto": sum(1 for m in models if m["lifecycle"] == "current" and m["cli"] == "auto-only"),
        "picker": sum(1 for m in models if m.get("app_picker_observed")),
        "auto": sum(1 for m in models if m.get("app_auto")),
    }


def full_text(model, catalog):
    doc = catalog["documents"].get(model.get("document"))
    if not doc:
        return "none (no card)"
    if doc["rights"] == "granted":
        name = "system-card.md" if doc["format"] == "pdf" else "model-card.md"
        return f"[committed]({model['slug']}/{name})"
    return "local workflow"


def doc_cell(model, catalog):
    doc = catalog["documents"].get(model.get("document"))
    if not doc:
        return f"[none]({model['slug']}/source.md)"
    pages = f", {doc['pages']} pp." if doc["pages"] else ", Markdown"
    return f"[{doc['title']}]({model['slug']}/source.md){pages}"


